// Prints the switch table of every engine that keeps its defaults in the shared profile::DefaultItem form.
//   strix-optimization-table            print the markdown table
//   strix-optimization-table --check F  fail unless F equals the table (docs/engine/optimization-table.md)
// The table is generated from the engines' own defaults tables; nothing here is maintained by hand.
#include "strix/deepseek41_pair_defaults.hpp"
#include "glm_rank_defaults.hpp"
#include "minimax/engine/mm_defaults.hpp"
#include "strix/qpf2k_defaults.hpp"

#include <fstream>
#include <iostream>
#include <iterator>
#include <sstream>
#include <string>
#include <string_view>

namespace {
void cell(std::ostream& out, std::string_view text) {
    for (const char c : text) {
        if (c == '|') out << "\\|";
        else if (c == '\n' || c == '\r') out << ' ';
        else out << c;
    }
}
void row(std::ostream& out, std::string_view engine, const strix::profile::DefaultItem& item) {
    out << "| " << engine << " | ";
    cell(out, item.name ? item.name : "");
    out << " | `";
    cell(out, item.env ? item.env : "");
    out << "` | ";
    cell(out, item.on ? item.on : "");
    out << " | ";
    cell(out, item.off ? item.off : "");
    out << " | ";
    cell(out, item.receipt ? item.receipt : "");
    out << " |\n";
}
std::string table() {
    std::ostringstream out;
    out << "<!-- Generated by strix-optimization-table; do not edit. -->\n"
           "# Engine switch table\n\n"
           "One row per default of each engine that keeps its table in the shared defaults form: the switch, its\n"
           "environment variable, the shipped value, the value that restores the previous path and the receipt text.\n\n"
           "| engine | switch | environment | default | off | receipt |\n|---|---|---|---|---|---|\n";
    for (const auto& item : strix::deepseek41::pair_defaults::default_items()) row(out, "deepseek41-pair", item);
    for (const auto& item : strix::glm::rank_defaults::env_items()) row(out, "glm-pair", item);
    for (const auto& item : strix::minimax::defaults::items()) row(out, "minimax-pair", item);
    for (const auto& item : strix::qpf2k::defaults) row(out, "qwen", item);
    return out.str();
}
} // namespace

int main(int argc, char** argv) {
    const std::string generated = table();
    if (argc == 3 && std::string_view(argv[1]) == "--check") {
        std::ifstream in(argv[2], std::ios::binary);
        std::string committed((std::istreambuf_iterator<char>(in)), std::istreambuf_iterator<char>());
        std::string stripped;
        for (const char c : committed) if (c != '\r') stripped.push_back(c);
        if (!in && stripped.empty()) { std::cerr << "cannot read " << argv[2] << '\n'; return 2; }
        if (stripped != generated) {
            std::cerr << argv[2] << " is stale: regenerate with strix-optimization-table > " << argv[2] << '\n';
            return 1;
        }
        return 0;
    }
    if (argc != 1) { std::cerr << "usage: strix-optimization-table [--check FILE]\n"; return 2; }
    std::cout << generated;
    return 0;
}
